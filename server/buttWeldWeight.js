const PI = 3.14159265;                      // the Deluge's own literal, not Math.PI
const txt = (v) => String(v == null ? '' : v).trim();

// '4" x 3" | SCH 40 (.237")' -> { mainDisp: '4" | SCH 40 (.237")', size2: '3"' }, exactly as the
// Deluge splits it. A trailing " STD" marker is dropped the same way Block C drops it.
function split(sizeDisplay) {
  let s = txt(sizeDisplay);
  let main = s, size2 = '';
  if (s.indexOf(' x ') > -1) {
    const combo = s.slice(0, s.indexOf(' | '));
    size2 = combo.slice(combo.indexOf(' x ') + 3).trim();
    main = combo.slice(0, combo.indexOf(' x ')).trim() + ' | ' + s.slice(s.indexOf(' | ') + 3);
  }
  if (/\sSTD$/.test(main)) main = main.replace(/\sSTD$/, '');
  return { mainDisp: main, size2: size2 };
}

// Returns { lb, basis } or null. NULL, never zero — a zero is an answer and would be summed.
function buttWeldFittingLb(opts) {
  opts = opts || {};
  const ftype = txt(opts.fitting_type);
  const connType = txt(opts.connection_type);
  const dens = Number(opts.density);
  if (!ftype || !(dens > 0)) return null;

  const { mainDisp, size2 } = split(opts.size_display);
  const dim = NPS_DIM[mainDisp];
  if (!dim) return null;                    // not a size/schedule the dimension table carries

  const od = dim[0], wall = dim[1];
  let nps = dim[2], teec = dim[3];
  const cape = dim[4];

  const area = PI * wall * (od - wall);
  let areaEff = area;
  if (size2) {
    const info = NPS_INFO[size2];
    if (info) {
      const od2 = info[0], nps2 = info[1], teec2 = info[2];
      const area2 = PI * wall * (od2 - wall);
      areaEff = (area + area2) / 2;
      // The Deluge keeps the LARGER end's nps and teec, which is why this compares.
      if (nps2 > nps) { nps = nps2; teec = teec2; }
    }
  }

  // bulk is 1.0 for butt weld (the 1.4 uplift is the forged branch), so it is left out.
  let vol;
  if (ftype === 'Cap') {
    vol = area * cape + PI / 4 * od * od * wall;
  } else if (ftype === 'Elbow') {
    let radius = nps;
    if (connType.indexOf('Long Radius') > -1) radius = nps * 1.5;
    let ang = 90.0;
    if (connType.indexOf('45') === 0) ang = 45.0;
    else if (connType.indexOf('180') === 0) ang = 180.0;
    vol = area * radius * ang * PI / 180.0;
  } else if (ftype === 'Reducer') {
    vol = areaEff * nps * 1.5;
  } else if (ftype === 'Tee') {
    vol = areaEff * 3 * teec;
  } else if (ftype === 'Cross') {
    vol = areaEff * 4 * teec;
  } else if (ftype === 'Stub End') {
    const len = Math.max(4.0, 0.5 * nps);
    vol = area * len;
  } else if (ftype === 'Coupling' || ftype === 'Union') {
    vol = areaEff * 2.5 * nps;
  } else if (ftype === 'Nipple') {
    // The Deluge assumes 4 inches. A nipple is cut pipe and its real length is not carried on
    // the row, so this is left to Deluge rather than reproducing a known-wrong assumption in a
    // second place. Measured on MCP-10009: 4" against the drawing's actual lengths is 1.9x heavy.
    return null;
  } else if (ftype === 'Plug') {
    vol = PI / 4 * od * od * 0.6 * nps;
  } else if (ftype === 'Bushing') {
    vol = areaEff * 0.8 * nps;
  } else if (ftype === 'Lateral / Y') {
    vol = areaEff * 4 * nps;
  } else if (ftype === 'Swage Nipple') {
    vol = areaEff * 3 * nps;
  } else if (ftype === 'Olet') {
    // getFittingWeight looks these up in getOletMap() with its own schedule tokens. Not ported:
    // an olet weight guessed here would disagree with the catalog one, and olets already price.
    return null;
  } else {
    vol = areaEff * 2.5 * nps;
  }

  if (!(vol > 0)) return null;
  return { lb: Number((vol * dens).toFixed(3)), basis: 'geometry (port of getFittingWeight)' };
}

